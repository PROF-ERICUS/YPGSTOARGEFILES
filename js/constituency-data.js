(function validateConstituencyData() {

    const expected = 276;

    const actual =
        constituencyData.length;


    const unique =
        new Set(
            constituencyData.map(
                function(item) {

                    return (
                        String(
                            item.constituency
                        )
                        .trim()
                        .toLowerCase()
                    );

                }
            )
        ).size;


    console.log(
        "YPG constituency records:",
        actual
    );


    console.log(
        "YPG unique constituency names:",
        unique
    );


    if (
        actual !== expected
    ) {

        console.warn(
            "Expected 276 constituency records, found " +
            actual
        );

    }


    if (
        unique !== actual
    ) {

        console.warn(
            "Duplicate constituency names detected."
        );

    }

})();